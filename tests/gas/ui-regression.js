// ทดสอบการใช้งานจริงบนมือถือ (ป้อนข้อมูลแปลกๆ / กดผิดวิธี) — เปิดเซิร์ฟเวอร์ก่อน: python3 -m http.server 8080
const { chromium } = require('playwright');
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log('  PASS', m); } else { fail++; console.log('  FAIL', m); } };
const APP = 'http://localhost:8080/index.html';

(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 375, height: 760 }, hasTouch: true, isMobile: true })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  p.on('dialog', (d) => d.dismiss());
  await p.goto(APP, { waitUntil: 'load' }); await p.waitForTimeout(1200);
  const recs = () => p.evaluate(() => JSON.parse(localStorage.getItem('ourWalletData') || '[]'));
  const submit = (id) => p.evaluate((i) => document.getElementById(i).requestSubmit(), id);
  const ym = new Date().toISOString().slice(0, 7);

  console.log('== forms save (catches runtime errors in submit handlers) ==');
  await p.evaluate(() => window.openModal('expenseModal')); await p.fill('#expDesc', 'ข้าว'); await p.fill('#expAmount', '10'); await submit('expenseForm'); await p.waitForTimeout(300);
  await p.evaluate(() => window.openModal('incomeModal')); await p.fill('#incDesc', 'เงินเดือน'); await p.fill('#incAmount', '1234.57'); await p.selectOption('#incTaxRate', '3'); await submit('incomeForm'); await p.waitForTimeout(300);
  const r = await recs();
  ok(r.length === 2, 'expense + income saved: ' + r.length);
  ok(r.find((t) => t.type === 'income').netAmount === 1197.53, 'net amount rounded to satang: ' + r.find((t) => t.type === 'income').netAmount);

  console.log('== hostile text is never executed ==');
  const evil = `<img src=x onerror="window.__xss=1">'"</script>`;
  await p.evaluate(() => window.openModal('expenseModal')); await p.fill('#expDesc', evil); await p.fill('#expAmount', '5'); await submit('expenseForm'); await p.waitForTimeout(400);
  ok(!(await p.evaluate(() => window.__xss === 1)) && (await p.$$eval('#transactionsList img', (e) => e.length)) === 0, 'no script/img injected into the list');
  const evilRec = (await recs()).find((t) => t.description === evil);
  await p.evaluate((id) => window.editItem(id), evilRec.id);
  ok((await p.inputValue('#expDesc')) === evil, 'text survives edit round trip'); await p.evaluate(() => window.closeModal());
  await p.evaluate(() => window.showToast('<b onclick="window.__t=1">x</b>', 'error'));
  ok((await p.$$eval('#toast-container b', (e) => e.length)) === 0, 'toast text is escaped');

  console.log('== month input ==');
  await p.fill('#monthSelector', ''); await p.dispatchEvent('#monthSelector', 'change'); await p.waitForTimeout(200);
  ok((await p.inputValue('#monthSelector')) === ym, 'clearing the month restores the current one');
  await p.evaluate(() => window.shiftMonth(-1)); await p.evaluate(() => window.shiftMonth(1));
  ok((await p.inputValue('#monthSelector')) === ym, 'prev/next arrows round trip');

  console.log('== limits ==');
  await p.evaluate(() => window.openModal('expenseModal')); await p.fill('#expDesc', 'x'); await p.fill('#expAmount', '100000000000');
  ok(!(await p.evaluate(() => document.getElementById('expenseForm').checkValidity())), 'absurd amount (>99,999,999.99) blocked');
  await p.fill('#expAmount', '-5');
  ok(!(await p.evaluate(() => document.getElementById('expenseForm').checkValidity())), 'negative amount blocked');
  await p.evaluate(() => window.closeModal());

  console.log('== recurring bills: renaming must not duplicate the series ==');
  await p.evaluate(() => window.openModal('expenseModal')); await p.fill('#expDesc', 'ผ่อนทีวี'); await p.selectOption('#expPayMode', 'installment');
  await p.fill('#expInstallAmount', '500'); await p.fill('#expCurInstall', '1'); await p.fill('#expTotalInstall', '6'); await p.fill('#expAmount', '500'); await submit('expenseForm'); await p.waitForTimeout(400);
  let tv = (await recs()).filter((t) => t.description === 'ผ่อนทีวี');
  ok(tv.length === 2 && tv.some((t) => t.autoGenerated), 'manual 1/6 + auto 2/6 next month');
  await p.evaluate((id) => window.editItem(id), tv.find((t) => !t.autoGenerated).id);
  await p.fill('#expDesc', 'ผ่อนทีวี Samsung'); await submit('expenseForm'); await p.waitForTimeout(500);
  const after = (await recs()).filter((t) => /ผ่อนทีวี/.test(t.description));
  ok(after.length === 2, 'still 2 bills after renaming (no duplicate): ' + after.map((t) => t.description + ':' + t.currentInstallment).join(' | '));
  await p.reload({ waitUntil: 'load' }); await p.waitForTimeout(800);
  ok((await recs()).filter((t) => /ผ่อนทีวี/.test(t.description)).length === 2, 'still 2 after reload');

  console.log('== layout ==');
  await p.evaluate((ymm) => localStorage.setItem('ourWalletData', JSON.stringify([
    { id: '1', type: 'income', date: ymm + '-01', monthYear: ymm, category: 'เงินเดือน', who: 'Anas', description: 'เงินเดือน', amount: 99999999.99, netAmount: 99999999.99, taxRate: 0 },
    { id: '2', type: 'expense', date: ymm + '-05', monthYear: ymm, category: 'อาหาร', who: 'Anas', description: 'ชื่อยาวมากๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆๆ LongWordWithoutSpacesLongWordWithoutSpacesLongWord', bank: 'KBank', amount: 45678901.23, isCompleted: false }])), ym);
  await p.reload({ waitUntil: 'load' }); await p.waitForTimeout(1800);
  ok(!(await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)), 'no horizontal scroll with max amounts and long names');

  ok(errs.length === 0, 'no page errors: ' + errs.join(' | '));
  console.log(`\n${pass} passed, ${fail} failed`);
  await b.close(); process.exit(fail ? 1 : 0);
})();
