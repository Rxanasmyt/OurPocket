console.log('== 10) batch, revision (fast sync) and error codes ==');
env = makeEnv({ sheets: ['Sheet1'] });
const b1 = env.post({ action: 'batch', items: [rec.income, rec.normal, { action: 'delete', id: 'nope' }, { type: 'bad', id: 'q' }, { action: 'budget', month: '2026-11', amount: 9000 }] });
ok(b1.status === 'success' && b1.results.map((x) => x.status).join() === 'success,success,success,error,success', 'batch results per item: ' + b1.results.map((x) => x.status).join());
ok(b1.results[3].code === 'invalid_record' && b1.results[3].message, 'rejected item has code + readable message: ' + b1.results[3].message);
const bs = env.ss.getSheetByName('รายการ');
ok(bs.getLastRow() === 3, 'batch wrote the 2 valid records');
const s1 = env.post({ action: 'sync' });
ok(typeof s1.rev === 'number' && s1.rev > 0, 'sync returns rev=' + s1.rev);
const s2 = env.post({ action: 'sync', since: s1.rev });
ok(s2.unchanged === true && !s2.data && s2.rev === s1.rev, 'same rev -> short "unchanged" reply (no sheet read)');
env.post(rec.minpay);
const s3 = env.post({ action: 'sync', since: s1.rev });
ok(!s3.unchanged && s3.data.length === 3 && s3.rev > s1.rev, 'after a write -> full data with new rev');
env.post({ action: 'delete', id: 'nope' });
ok(env.post({ action: 'sync', since: s3.rev }).unchanged === true, 'no-op delete does not bump rev');
env.post({ action: 'delete', id: 'm1' });
ok(env.post({ action: 'sync', since: s3.rev }).unchanged !== true, 'real delete bumps rev');
const bad = JSON.parse(env.ctx.doPost({ postData: { contents: 'not json' } }).text);
ok(bad.status === 'error' && bad.code === 'bad_request', 'garbled body -> code bad_request');
ok(env.post({ action: 'whatever' }).code === 'bad_request', 'unknown action -> bad_request');
const lk = makeEnv({ sheets: ['Sheet1'], lockFail: true });
const lockRes = lk.post(rec.income);
ok(lockRes.code === 'lock_timeout' && lockRes.message.includes('ลองใหม่'), 'lock failure -> code lock_timeout with advice');
ok(lk.post({ action: 'sync' }).status === 'success', 'reads still work when lock is busy');
ok(env.get({}).includes('Our Wallet script v8'), 'GET shows API version string the app checks: ' + env.get({}));

