const { makeEnv } = require('./mock');
const assert = require('assert');
let pass = 0, fail = 0;
const ok = (cond, msg) => { if (cond) { pass++; console.log('  PASS', msg); } else { fail++; console.log('  FAIL', msg); } };

const rec = {
  income: { id: 'i1', type: 'income', date: '2026-11-01', monthYear: '2026-11', category: 'เงินเดือน', who: 'Anas', description: 'เงินเดือน', amount: 30000, taxRate: 3, netAmount: 29100, timestamp: 1 },
  normal: { id: 'e1', type: 'expense', date: '2026-11-20', monthYear: '2026-11', category: 'ที่พัก', who: 'Phada', description: 'ค่าไฟ', bank: 'กรุงศรี', amount: 2500, isCompleted: false, payMode: 'normal', fullAmount: null, minAmount: null, installmentAmount: null, remainingAmount: null, currentInstallment: null, totalInstallments: null, timestamp: 2 },
  minpay: { id: 'm1', type: 'expense', date: '2026-11-10', monthYear: '2026-11', category: 'หนี้สิน', who: 'Anas', description: 'บัตร KTC', bank: 'KTB', amount: 3000, isCompleted: true, payMode: 'minpay', fullAmount: 20000, minAmount: 1000, installmentAmount: null, remainingAmount: 17000, currentInstallment: null, totalInstallments: null, timestamp: 3 },
  inst: { id: 'auto-abc-2026-11', type: 'expense', date: '2026-11-25', monthYear: '2026-11', category: 'หนี้สิน', who: 'Phada', description: 'ผ่อนมือถือ', bank: 'SCB', amount: 1500, isCompleted: false, payMode: 'installment', fullAmount: null, minAmount: null, installmentAmount: 1500, remainingAmount: null, currentInstallment: '3', totalInstallments: '5', autoGenerated: true, timestamp: 4 }
};

console.log('== 1) fresh spreadsheet, first save ==');
let env = makeEnv({ sheets: ['Sheet1'] });
let r = env.post(rec.income);
ok(r.status === 'success', 'income saved: ' + JSON.stringify(r));
const names = env.sheets.map((s) => s.name);
ok(JSON.stringify(names) === JSON.stringify(['สรุป', 'ลำดับจ่าย', 'รายเดือน', 'ค้นหา', 'รายการ', 'ตั้งค่า']), 'tab order: ' + names.join(' | '));
ok(env.props.get('setupErrors') === '', 'no setup errors: "' + env.props.get('setupErrors') + '"');
const data = env.ss.getSheetByName('รายการ');
const hdr = data.getRange(1, 1, 1, data.getLastColumn()).getValues()[0];
ok(hdr.length === 22, 'headers = 22: ' + hdr.length);
const row = (n) => { const o = {}; data.getRange(n, 1, 1, hdr.length).getValues()[0].forEach((v, i) => (o[hdr[i]] = v)); return o; };
let r2 = row(2);
ok(r2['ประเภท'] === 'รายรับ' && r2['จำนวนเงิน'] === 29100 && r2['ยอดก่อนหัก'] === 30000 && r2['หัก ณ ที่จ่าย %'] === 3 && r2['ที่มา'] === 'กรอกเอง', 'income row complete: ' + JSON.stringify(r2).slice(0, 220));
ok(r2['ธนาคาร'] === '-' && r2['งวดที่'] === '' && r2['คงค้าง'] === '', 'income has blanks (not "-") in numeric cols');
ok(!JSON.stringify(r2).includes('secret'), 'no key in row');

console.log('== 2) all bill types ==');
['normal', 'minpay', 'inst'].forEach((k) => ok(env.post(rec[k]).status === 'success', 'saved ' + k));
ok(data.getLastRow() === 5, 'rows = 4 records: lastRow=' + data.getLastRow());
let m = row(4), n = row(3), i = row(5);
ok(n['รูปแบบการจ่าย'] === 'จ่ายปกติ' && n['ยอดเต็มบิล'] === '' && n['สถานะ'] === 'รอดำเนินการ' && n['ธนาคาร'] === 'กรุงศรี', 'normal bill row');
ok(m['รูปแบบการจ่าย'] === 'ผ่อนบัตร: จ่ายขั้นต่ำ' && m['ยอดเต็มบิล'] === 20000 && m['ขั้นต่ำ / ต่องวด'] === 1000 && m['คงค้าง'] === 17000 && m['สถานะ'] === 'เสร็จสิ้น', 'minpay row: ' + JSON.stringify([m['ยอดเต็มบิล'], m['ขั้นต่ำ / ต่องวด'], m['คงค้าง']]));
ok(i['รูปแบบการจ่าย'] === 'ผ่อนบัตร: จ่ายเป็นงวด' && i['งวดที่'] === 3 && i['รวมงวด'] === 5 && i['ขั้นต่ำ / ต่องวด'] === 1500 && i['ที่มา'] === 'สร้างอัตโนมัติ', 'installment row (numeric งวด): ' + JSON.stringify([i['งวดที่'], i['รวมงวด'], i['ขั้นต่ำ / ต่องวด'], i['ที่มา']]));

console.log('== 3) upsert / delete / budget / sync ==');
const savedAt = row(3)['บันทึกเมื่อ'];
env.post({ ...rec.normal, isCompleted: true, amount: 2600 });
ok(data.getLastRow() === 5, 'update does not add a row');
ok(row(3)['สถานะ'] === 'เสร็จสิ้น' && row(3)['จำนวนเงิน'] === 2600, 'update applied');
ok(row(3)['บันทึกเมื่อ'] === savedAt, 'saved-at preserved on update');
ok(env.post({ action: 'delete', id: 'e1' }).status === 'success' && data.getLastRow() === 4, 'delete removes row');
ok(env.post({ action: 'delete', id: 'e1' }).message === 'already deleted', 'delete is idempotent');
ok(env.post({ action: 'budget', month: '2026-11', amount: 15000 }).status === 'success', 'budget saved');
env.post({ action: 'budget', month: '2026-11', amount: 18000 });
let sync = env.post({ action: 'sync' });
ok(sync.data.length === 3 && sync.budgets['2026-11'] === 18000, 'sync returns 3 records + budget');
const inst = sync.data.find((x) => x.id === rec.inst.id);
ok(JSON.stringify(inst) === JSON.stringify(rec.inst), 'sync returns original JSON unchanged (round-trip)');
ok(env.post({ type: 'weird', id: 'z' }).status === 'error', 'invalid record rejected');
ok(env.post({ type: 'income' }).status === 'error', 'record without id rejected');

console.log('== 4) key protection ==');
env = makeEnv({ sheets: ['Sheet1'], props: { WALLET_KEY: 'k3y' } });
ok(env.post({ action: 'sync' }).code === 'unauthorized', 'no key -> unauthorized');
ok(env.post({ action: 'sync', key: 'bad' }).code === 'unauthorized', 'wrong key -> unauthorized');
ok(env.post({ ...rec.income, key: 'bad' }).code === 'unauthorized', 'write with wrong key blocked');
ok(env.post({ ...rec.income, key: 'k3y' }).status === 'success', 'write with key ok');
ok(env.get({ action: 'sync' }).includes('unauthorized'), 'GET sync blocked when key set');
const d2 = env.ss.getSheetByName('รายการ');
let leak = false; for (const v of d2.cells.values()) if (String(v).includes('k3y')) leak = true;
ok(!leak, 'key not written anywhere in the sheet');
ok(env.post({ action: 'sync', key: 'k3y' }).data.length === 1, 'sync with key ok');

console.log('== 5) ping / selftest ==');
let pr = env.post({ action: 'ping', key: 'k3y' });
ok(pr.status === 'success' && pr.keyProtected === true && pr.rows === 1, 'ping: ' + JSON.stringify(pr));
let st = env.post({ action: 'selftest', key: 'k3y' });
ok(st.status === 'success' && st.write && st.read && st.delete && st.rows === 1, 'selftest write/read/delete ok, leaves no row: ' + JSON.stringify(st));

console.log('== 6) legacy sheet (old 18-col layout) migrates without losing data ==');
env = makeEnv({ sheets: ['Sheet1'] });
const old = env.ss.getSheetByName('Sheet1');
const OLD = ['ประเภท', 'วันที่', 'เดือน-ปี', 'หมวดหมู่', 'รายการ', 'คนทำรายการ', 'ธนาคาร', 'งวดที่', 'รวมงวด', 'จำนวนเงิน', 'สถานะ', 'บันทึกเมื่อ', 'ID', 'RAW_JSON', 'รูปแบบการจ่าย', 'ยอดเต็มบิล', 'ขั้นต่ำ / ต่องวด', 'คงค้าง'];
OLD.forEach((h, c) => old.set(1, c + 1, h));
const legacy = { id: 'old1', type: 'expense', date: '2026-10-05', monthYear: '2026-10', category: 'อาหาร', who: 'ฉัน', description: 'ข้าว', bank: 'เงินสด', amount: 120, isCompleted: true, currentInstallment: null, totalInstallments: null };
const legacyRow = ['รายจ่าย', '2026-10-05', '2026-10', 'อาหาร', 'ข้าว', 'ฉัน', 'เงินสด', '-', '-', 120, 'เสร็จสิ้น', '05/10/2026 12:00:00', 'old1', JSON.stringify(legacy), 'จ่ายปกติ', '-', '-', '-'];
legacyRow.forEach((v, c) => old.set(2, c + 1, v));
env.post({ action: 'sync' });
const dh = old.getRange(1, 1, 1, old.getLastColumn()).getValues()[0];
ok(old.name === 'รายการ' && dh.length === 22 && dh.slice(0, 18).join() === OLD.join(), 'old sheet renamed + 4 columns appended after the old 18: ' + dh.length);
const lr = {}; old.getRange(2, 1, 1, dh.length).getValues()[0].forEach((v, i) => (lr[dh[i]] = v));
ok(lr['ID'] === 'old1' && lr['จำนวนเงิน'] === 120 && lr['บันทึกเมื่อ'] === '05/10/2026 12:00:00', 'legacy row preserved (id, amount, original saved-at)');
ok(lr['ยอดเต็มบิล'] === '' && lr['งวดที่'] === '' && lr['ที่มา'] === 'กรอกเอง', "legacy '-' placeholders cleaned to blanks, new columns backfilled");
ok(env.post({ ...legacy, amount: 150 }).status === 'success' && old.getLastRow() === 2 && old.getRange(2, 10).getValue() === 150, 'editing legacy record updates same row (no duplicate)');
ok(env.post({ action: 'sync' }).data.length === 1, 'legacy record visible to app');

console.log('== 7) checkData ==');
const chk = env.ctx.checkData_(old);
ok(chk.rows === 1 && chk.noJson === 0 && chk.duplicates === 0 && chk.mismatch === 0, 'clean data: ' + JSON.stringify(chk));
old.set(2, 10, 999999); // manual edit in sheet
const chk2 = env.ctx.checkData_(old);
ok(chk2.mismatch === 1, 'manual edit in sheet detected: ' + JSON.stringify(chk2));
env.ctx.refreshRows_(old);
ok(old.getRange(2, 10).getValue() === 150 && env.ctx.checkData_(old).mismatch === 0, 'refreshAll restores sheet from JSON');

console.log('== 8) user-added extra column survives updates ==');
env = makeEnv({ sheets: ['Sheet1'] });
env.post(rec.income);
const ds = env.ss.getSheetByName('รายการ');
ds.set(1, 22, 'โน้ตของฉัน'); ds.set(2, 22, 'โบนัสพิเศษ');
env.post({ ...rec.income, amount: 31000, netAmount: 30070 });
ok(ds.get(2, 22) === 'โน้ตของฉัน'.length ? false : ds.get(2, 22) === 'โบนัสพิเศษ', 'user column value kept after update');
console.log('== 9) junk rows from an old script are purged, never reach the app ==');
env = makeEnv({ sheets: ['Sheet1'] });
const jd = env.ss.getSheetByName('Sheet1');
OLD.forEach((h, c) => jd.set(1, c + 1, h));
const junkRow = (json) => ['รายจ่าย', '-', '-', '-', '-', '-', '-', '-', '-', 0, 'รอดำเนินการ', '08/11/2026 10:00:00', '-', json, 'จ่ายปกติ', '-', '-', '-'];
junkRow(JSON.stringify({ action: 'sync', key: 'topsecret' })).forEach((v, c) => jd.set(2, c + 1, v));
legacyRow.forEach((v, c) => jd.set(3, c + 1, v));
junkRow(JSON.stringify({ action: 'selftest' })).forEach((v, c) => jd.set(4, c + 1, v));
['พิมพ์เอง', '2026-10-09', '2026-10', 'อาหาร', 'ข้าวที่พิมพ์เองในชีต'].forEach((v, c) => jd.set(5, c + 1, v));
const syncJ = env.post({ action: 'sync' });
