let hasKey = false; for (const v of dj.cells.values()) if (String(v).includes('topsecret')) hasKey = true;
ok(syncJ.data.length === 1 && syncJ.data[0].id === 'old1', 'app only receives the 1 valid record: ' + syncJ.data.length);
ok(!hasKey, 'row that had leaked key text was deleted from the sheet');
ok(dj.getLastRow() === 3, 'junk rows removed (kept legacy record + hand-typed row): lastRow=' + dj.getLastRow());
